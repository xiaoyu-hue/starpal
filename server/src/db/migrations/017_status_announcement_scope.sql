-- 迁移 017：修正「当前进度与已知问题」的口径（M5 收尾）
-- 对应 IMPLEMENTATION-PLAN.md M5 段末「M5 收尾」与 PRD.md §4.11 实现状态说明。
-- 依赖：016 已建 announcements 表并写入该条种子。
-- 回滚影响：仅改文本，无结构变化；如需还原，把 summary / body 改回 016 的原文即可。
--
-- 为什么不能直接改 016：
--   016 已在本机与线上（Vercel 冷启动）执行完毕，迁移只增不改是硬规矩。
--   且 016 的安装记录以 version 为键，改文件内容不会重跑，改了也不生效。
--
-- 两处修正：
--   ① 摘要自相矛盾。原文写「暂无公示的未完成项」，而正文明确写着
--      「尚未开始：经验 / 签到 / 等级，完整治理后台与审核日志，验收与性能加固」。
--      右栏卡片只显示摘要，用户会以为全站已完工——这与 M5 之前「私信仍在开发中」
--      属同一类错误：摘要替正文说了不负责任的话。
--   ② 通知范围需要对外说清。M5 收尾确认只做「评论」一种通知（PRD FR-AUX-01 已记偏差），
--      点赞 / 收藏 / 私信 / 公告都不发通知；不写清楚，用户会等一个永远不会来的提醒。

-- 条件化更新：只在文本仍是 016 原文时才改。
-- 运营者此后在「运营管理 → 社区公告」里的手动编辑不会被本迁移覆盖。
UPDATE announcements
   SET summary    = '站点可用。核心功能已交付；经验 / 签到 / 等级与完整治理后台尚未开始。',
       updated_at = now()
 WHERE kind = 'status'
   AND title = '当前进度与已知问题'
   AND summary = '站点可用。私信、搜索、成就时间线、每周热门与数据导出均已交付，暂无公示的未完成项。';

-- 正文追加通知范围说明。用 NOT LIKE 兜住重复执行，也不覆盖运营者自己写过的同一句话。
UPDATE announcements
   SET body = body
              || E'\n通知只在你收到评论时发出：别人赞你的帖子、收藏你的帖子、给你发私信，都不会单独提醒——私信请在私信列表里查看。',
       updated_at = now()
 WHERE kind = 'status'
   AND title = '当前进度与已知问题'
   AND body NOT LIKE '%通知只在你收到评论时发出%';
