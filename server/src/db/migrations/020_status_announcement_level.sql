-- 回滚影响：仅改文本，无结构变化；还原即把该段改回 016 原文。
--
-- 为什么还要改正文：
--   016 的正文写着「尚未开始：经验 / 签到 / 等级，完整治理后台与审核日志，验收与性能加固」，
--   而同一段结尾又写着「不做排行榜、不做签到」——既说「尚未开始」又说「不做」，
--   同一行里自相矛盾。现在经验与等级已交付、签到经评审取消，两句话都该改。
--   这与 017 / 018 修的摘要漂移是同一个病根：公告正文若枚举「还没做的事」，
--   每完成一件就会变成一句假话。
--
-- 条件化替换：只替换仍是原文的那一段，运营者此后在后台的编辑不会被覆盖。
-- 用子串 replace 而非整段覆盖，是因为 017 在正文末尾追加过一句，
-- 整段匹配会因末尾差异而匹配不上，导致这次修正静默失效。
UPDATE announcements
   SET body = replace(
         body,
         '尚未开始：经验 / 签到 / 等级，完整治理后台与审核日志，验收与性能加固。',
         E'等级与段位已上线：个人页显示等级 L1–L50 与段位（萌新 / 入门 / 常客 / 老友 / 元老），经验按发帖、评论、收到的赞、覆盖的话题、邀请与加入天数累计，只升不降。\n尚未开始：完整治理后台与审核日志，验收与性能加固。'
       ),
       updated_at = now()
 WHERE kind = 'status'
   AND title = '当前进度与已知问题'
   AND body LIKE '%尚未开始：经验 / 签到 / 等级，完整治理后台与审核日志，验收与性能加固。%';
