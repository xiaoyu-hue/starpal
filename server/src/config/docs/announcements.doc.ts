/**
 * 社区公告条目：按时间倒序，最新在前。
 *
 * 公告属运营信息而非用户内容，随代码版本化、不入库：改文案即发版，
 * 避免「公告写死在某个页面里、另一处还留着旧版本」的漂移。
 * 右侧栏卡片与 /announcements 页读同一份数据，只有一个真相源。
 *
 * 写法参照 Discourse / GitHub Releases / Reddit 的更新通告惯例：
 * 1. 每条带类型标签（新增 / 修复 / 规则 / 状态），便于扫描，不必逐字读。
 * 2. 先给一句摘要，再列明细；明细写「变化 + 对你的影响」，不写实现细节。
 * 3. 需要用户配合的，单独给一句「需要你做什么」；没有就留空，不硬凑。
 * 4. 已知问题单独成条并写清哪些地方会「点进去是空的」——
 *    把缺口写在明处，比让用户自己撞见一扇打不开的门要好。
 * 5. 不含版本号：公告是运营信息，版本信息以 CHANGELOG 与 Release 为准；
 *    发版后依然不在此写版本号，避免把运营通告与代码版本绑在一起。
 */

